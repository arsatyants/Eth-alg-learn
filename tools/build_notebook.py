md(r"""
## 6. Subset Sum: три уровня перебора

Даны $a_0,\dots,a_{n-1}$ и $T$; найти маску $S$ с $\sum_{i\in S}a_i=T$.

### 6.1 Наивный перебор: $O(n\cdot2^n)$
Для каждой из $2^n$ масок заново складываем до $n$ чисел.

### 6.2 Код Грея: $O(2^n)$
Рефлексивный код Грея $g(i)=i\oplus(i\gg1)$ обходит все маски так, что соседние отличаются **одним** битом.

**Какой бит меняется.** $g(i)\oplus g(i-1) = (i\oplus(i-1)) \oplus ((i\oplus(i-1))\gg1)$.
Число $i\oplus(i-1)$ имеет вид $0\dots01\dots1$ с $t+1$ единицами, где $t=\mathrm{ctz}(i)$ (число младших нулей $i$).
После XOR со сдвигом остаётся одна единица в позиции $t$. Итак:
$$\text{на шаге } i \text{ меняется бит } \mathrm{ctz}(i),\quad\text{новое значение } g(i)_{\mathrm{ctz}(i)}.$$
Если бит стал 1, элемент вошёл в подмножество: $s \mathrel{+}= a_{\mathrm{ctz}(i)}$; если стал 0 — вышел: $s \mathrel{-}= a_{\mathrm{ctz}(i)}$.
Одно сложение на маску. Это ровно то, что делает `ss_engine.v`.
""")

code(r"""
print(f"{'i':>2} {'bin(i)':>7} {'ctz':>4} {'g(i)':>6} {'dir':>4}  действие")
for i in range(1, 16):
    t = (i & -i).bit_length() - 1
    g = i ^ (i >> 1)
    d = g >> t & 1
    print(f"{i:>2} {i:07b} {t:>4} {g:06b} {d:>4}  {'+' if d else '-'}a[{t}]")
""")

md(r"""
### 6.3 Meet-in-the-middle: $O(2^{n/2}\cdot n)$, основание $\sqrt2\approx1.414$
Разбиваем числа на две половины $A$ и $B$ по $n/2$. Любая маска — это пара $(S_A,S_B)$, и
$$\sum S_A + \sum S_B = T \iff \sum S_B = T-\sum S_A.$$
1. Перечислить все $2^{n/2}$ сумм $B$ и отсортировать: $O(2^{n/2}\,n)$;
2. для каждой из $2^{n/2}$ сумм $A$ найти $T-s$ бинарным поиском: $O(2^{n/2}\,n)$.

Итог $2^{n/2}=(\sqrt2)^n$ при памяти $2^{n/2}$ (Горовиц–Сахни, 1974). Шрёппель–Шамир (1981) снижают память
до $2^{n/4}$ при том же времени. Это **алгоритмическое** уменьшение основания: две половины независимы,
поэтому вместо произведения $2^{n/2}\cdot2^{n/2}$ работа складывается: $2^{n/2}+2^{n/2}$.

### 6.4 Псевдополиномиальное ДП: $O(nT)$
Битсет достижимых сумм. Полиномиально по **значению** $T$, но экспоненциально по **длине записи** $\log T$.
С ETH это не конфликтует: задача трудна, когда числа имеют $\Theta(n)$ бит.
""")

